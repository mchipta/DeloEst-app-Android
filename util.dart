String ssLabel(Map<String, String> s) {
  final parts = <String>[
    s['q'] ?? '',
    s['type'] ?? '',
    s['cat'] ?? '',
    s['city'] ?? '',
    (s['min'] ?? '').isEmpty ? '' : 'от ${s['min']} ₽',
    (s['max'] ?? '').isEmpty ? '' : 'до ${s['max']} ₽',
    s['sort'] == 'hi' ? 'дороже' : s['sort'] == 'lo' ? 'дешевле' : '',
  ].where((e) => e.isNotEmpty).toList();
  return parts.join(' · ');
}

