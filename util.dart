String digitsOnly(String s) => s.replaceAll(RegExp(r'\D'), '');

// 8XXXXXXXXXX и 10 цифр приводим к 7XXXXXXXXXX
String normPhone(String v) {
  var d = digitsOnly(v);
  if (d.length == 11 && d.startsWith('8')) d = '7${d.substring(1)}';
  if (d.length == 10) d = '7$d';
  return d;
}

// +7 (999) 123-45-67
String fmtPhone(String v) {
  var d = digitsOnly(v);
  if (d.isEmpty) return '';
  if (d.startsWith('8')) {
    d = '7${d.substring(1)}';
  } else if (d.startsWith('9') && d.length <= 10) {
    d = '7$d';
  }
  String part(String s, int a, int b) => s.length <= a ? '' : s.substring(a, s.length < b ? s.length : b);
  String clip(String s, int n) => s.length > n ? s.substring(0, n) : s;
  if (d.startsWith('7')) {
    d = clip(d, 11);
    final a = part(d, 1, 4), b = part(d, 4, 7), c = part(d, 7, 9), e = part(d, 9, 11);
    return '+7${a.isEmpty ? '' : ' ($a${a.length == 3 ? ')' : ''}'}${b.isEmpty ? '' : ' $b'}${c.isEmpty ? '' : '-$c'}${e.isEmpty ? '' : '-$e'}';
  }
  if (d.startsWith('375')) {
    d = clip(d, 12);
    final a = part(d, 3, 5), b = part(d, 5, 8), c = part(d, 8, 10), e = part(d, 10, 12);
    return '+375${a.isEmpty ? '' : ' ($a${a.length == 2 ? ')' : ''}'}${b.isEmpty ? '' : ' $b'}${c.isEmpty ? '' : '-$c'}${e.isEmpty ? '' : '-$e'}';
  }
  if (d.startsWith('998')) {
    d = clip(d, 12);
    final a = part(d, 3, 5), b = part(d, 5, 8), c = part(d, 8, 10), e = part(d, 10, 12);
    return '+998${a.isEmpty ? '' : ' $a'}${b.isEmpty ? '' : ' $b'}${c.isEmpty ? '' : '-$c'}${e.isEmpty ? '' : '-$e'}';
  }
  return '+${clip(d, 15)}';
}

/// Номер введён полностью: 11 цифр для +7, 12 для +375 и +998
bool phoneComplete(String norm) {
  final d = digitsOnly(norm);
  if (d.startsWith('7')) return d.length == 11;
  if (d.startsWith('375') || d.startsWith('998')) return d.length == 12;
  return d.length >= 11 && d.length <= 15;
}

class PhoneFormatter extends TextInputFormatter {
  @override
  TextEditingValue formatEditUpdate(TextEditingValue oldV, TextEditingValue newV) {
    var d = digitsOnly(newV.text);
    if (newV.text.length < oldV.text.length && digitsOnly(oldV.text) == d && d.isNotEmpty) {
      d = d.substring(0, d.length - 1);
    }
    final t = fmtPhone(d);
    return TextEditingValue(text: t, selection: TextSelection.collapsed(offset: t.length));
  }
}

// 12 500
String grp(String s) {
  final d = digitsOnly(s);
  final t = d.length > 9 ? d.substring(0, 9) : d;
  final b = StringBuffer();
  for (var i = 0; i < t.length; i++) {
    if (i > 0 && (t.length - i) % 3 == 0) b.write(' ');
    b.write(t[i]);
  }
  return b.toString();
}

class GroupFormatter extends TextInputFormatter {
  @override
  TextEditingValue formatEditUpdate(TextEditingValue oldV, TextEditingValue newV) {
    final t = grp(newV.text);
    return TextEditingValue(text: t, selection: TextSelection.collapsed(offset: t.length));
  }
}

