Map<String, String>? _legalCache;

Future<Map<String, String>> loadLegal({bool force = false}) async {
  if (_legalCache != null && !force) return _legalCache!;
  final n = Map<String, String>.of(kLegalDefaults);
  try {
    final j = await Api.call('legal');
    final s = (j['legal'] ?? '').toString();
    if (s.isNotEmpty) {
      final m = jsonDecode(s) as Map;
      for (final k in kLegalTitles.keys) {
        final v = (m[k] ?? '').toString();
        if (v.trim().isNotEmpty) n[k] = v;
      }
    }
    _legalCache = n;
  } catch (_) {
    // нет сети — показываем встроенные тексты, но не запоминаем, чтобы в следующий раз попробовать снова
  }
  return n;
}

void openLegal(BuildContext context, String doc) {
  Navigator.push(context, MaterialPageRoute(builder: (_) => LegalPage(doc: doc)));
}

class LegalPage extends StatefulWidget {
  final String doc;
  const LegalPage({super.key, this.doc = 'offer'});
  @override
  State<LegalPage> createState() => _LegalPageState();
}

class _LegalPageState extends State<LegalPage> {
  Map<String, String> c = Map<String, String>.of(kLegalDefaults);
  late String doc;
  bool loading = true;

  @override
  void initState() {
    super.initState();
    doc = kLegalTitles.containsKey(widget.doc) ? widget.doc : 'offer';
    _load();
  }

  Future<void> _load() async {
    final n = await loadLegal();
    if (mounted) {
      setState(() {
        c = n;
        loading = false;
      });
    }
  }

  Widget _chip(Pal p, String k) {
    final on = doc == k;
    return Padding(
      padding: const EdgeInsets.only(right: 8),
      child: Tap(
        onTap: () => setState(() => doc = k),
        scale: .96,
        child: Container(
          padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 9),
          decoration: BoxDecoration(
            color: on ? p.ac : p.card,
            borderRadius: BorderRadius.circular(99),
            border: Border.all(color: on ? p.ac : p.bd),
          ),
          child: Text(kLegalShort[k]!,
              style: TextStyle(fontSize: 13.5, fontWeight: FontWeight.w700, color: on ? Colors.white : p.tx)),
        ),
      ),
    );
  }

  List<Widget> _body(Pal p) {
    final blocks = (c[doc] ?? '').split(RegExp(r'\n\s*\n')).map((x) => x.trim()).where((x) => x.isNotEmpty).toList();
    final out = <Widget>[];
    for (var i = 0; i < blocks.length; i++) {
      final b = blocks[i];
      if (b.startsWith('## ')) {
        out.add(Padding(
          padding: const EdgeInsets.only(top: 18, bottom: 6),
          child: Text(b.substring(3), style: TextStyle(fontSize: 16.5, fontWeight: FontWeight.w800, color: p.tx, height: 1.3)),
        ));
      } else {
        final date = i == 0 && b.startsWith('Редакция');
        out.add(Padding(
          padding: const EdgeInsets.only(bottom: 10),
          child: SelectableText(b,
              style: TextStyle(fontSize: date ? 12.5 : 14.5, height: 1.55, color: p.mu)),
        ));
      }
    }
    return out;
  }

  @override
  Widget build(BuildContext context) {
    final p = pal(context);
    return Scaffold(
      appBar: AppBar(title: const Text('Документы')),
      body: SafeArea(
        child: ListView(padding: const EdgeInsets.fromLTRB(20, 4, 20, 28), children: [
          SingleChildScrollView(
            scrollDirection: Axis.horizontal,
            child: Row(children: [for (final k in kLegalTitles.keys) _chip(p, k)]),
          ),
          const SizedBox(height: 14),
          Text(kLegalTitles[doc]!, style: TextStyle(fontSize: 22, fontWeight: FontWeight.w800, color: p.tx, height: 1.25)),
          const SizedBox(height: 8),
          if (loading) LinearProgressIndicator(color: p.ac, backgroundColor: p.bd, minHeight: 2),
          ..._body(p),
        ]),
      ),
    );
  }
}
